# Quiz 4 guide and direct solver entry points.
import STCORE as c

DICE='QZ401: TWO FAIR INDEPENDENT DICE HAVE 36 ORDERED PAIRS (FIRST,SECOND). SUM 3: (1,2),(2,1), P=2/36=1/18. SUM 7: (1,6),(2,5),(3,4),(4,3),(5,2),(6,1), P=6/36=1/6. ODD SUM: ONE ODD AND ONE EVEN, 18/36=1/2. SUM 3 OR 7: 8/36=2/9. AT LEAST ONE EVEN: 1-(3/6)^2=27/36=3/4. FIVE DICE: 6^5=7776 OUTCOMES. AT LEAST ONE 3: COMPLEMENT OF NO 3. TWO DICE: 1-(5/6)^2=11/36=.3056; FIVE: 1-(5/6)^5=4651/7776=.5981. ONE DIE HAS FIVE NON-3 FACES. COUNT (3,3) ONCE. OPEN DICE SOLVER, ENTER 2; SAMPLE SPACE IS OPTION 4. DESCRIBE EVENT THEN CHOOSE LIST MATCHING OUTCOMES. FOR FIVE DICE ENTER 5; EVENT 5 IS AT LEAST ONE FACE.'
SURVEY='QZ402: TOTAL 450; A=COMPOST 184; B=RECYCLE 238; BOTH 123. A ONLY 61; B ONLY 115; NEITHER 151. OR=184+238-123=299. TABLE COLUMNS B,NOT B: ROW A 123,61; ROW NOT A 115,151. CIRCLE 61 FOR COMPOST BUT NOT RECYCLE. P(A NOT B)=61/450=.1356. P(B GIVEN A)=123/184=.6685. THREE ALL RECYCLE WITHOUT REPLACEMENT: (238/450)*(237/449)*(236/448)=.1471. WITH REPLACEMENT: (238/450)^3=.1479. n/N=3/450=.006667, BELOW .05. THE 5% GUIDELINE ALLOWS THE INDEPENDENCE APPROXIMATION .1479, BUT EXACT WITHOUT REPLACEMENT IS .1471. OPEN VENN SOLVER AND ENTER 450,184,238,123. OPTION 5 SELECTS FROM B; ENTER 3. RETAIN SAME COUNTS FOR OTHER PARTS.'


def quiz_menu():
    while True:
        key=c.menu('QUIZ 4 / PROBABILITY',[('1','QZ401 DICE WORKED EXAMPLE'),('2','QZ402 SURVEY WORKED EXAMPLE'),('3','OPEN DICE SOLVER'),('4','OPEN VENN COUNTS'),('5','ALL SELECTED / 5% RULE')])
        if key=='0': return
        if key in ('1','2'): c.call('STSTUDY','definition_pages','QUIZ 4 WORKED ANSWER',DICE if key=='1' else SURVEY)
        else: c.call(*{'3':('STDICE','dice_session'),'4':('STVENN','venn_session'),'5':('STVENN','selection_session')}[key])
