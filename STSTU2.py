import STCORE
from STSTUDY import definition_pages, definition_list, SAMPLING_DEFINITIONS, MEASUREMENT_DEFINITIONS, STUDY_DEFINITIONS, BIAS_DEFINITIONS, DEFINITIONS
def sampling_menu():
  while True:
    key=STCORE.menu('STUDY > SAMPLING',[('1','IDENTIFY SELECTION METHOD'),('2','VIEW METHODS'),('3','CHECK FRAME / SURVEY BIAS')])
    if key=='0': return
    if key=='2': definition_list('STUDY > METHODS',SAMPLING_DEFINITIONS)
    elif key=='3': definition_list('SURVEY BIAS / QUOTAS',BIAS_DEFINITIONS)
    else:
      method=STCORE.menu('HOW ARE PEOPLE SELECTED?', [('1','EVERY kth PERSON'),('2','RANDOM FROM EVERY GROUP'),('3','RANDOM WHOLE GROUPS'),('4','PEOPLE CHOOSE TO RESPOND'),('5','FILL SUBGROUP QUOTAS'),('6','EASIEST PEOPLE TO REACH'),('7','ALL SIZE-n SUBSETS EQUALLY'),('8','EACH PERSON EQUALLY'),('9','GROUPS THEN SOME MEMBERS')])
      if method=='0': continue
      if method in ('1','2','3','6','7','8'):
        definition_pages(*SAMPLING_DEFINITIONS[{'1':2,'2':4,'3':5,'6':3,'7':0,'8':1}[method]])
      elif method=='9': definition_pages(*DEFINITIONS[-1])
      else: definition_pages(*BIAS_DEFINITIONS[0 if method=='4' else 3])
      definition_pages('METHOD VERSUS BIAS','THE SELECTION METHOD AND REPRESENTATIVENESS ARE SEPARATE. EVERY TENTH LIBRARY VISITOR IS SYSTEMATIC, BUT EXCLUDES NONVISITORS. SAMPLING MENU 3 EXPLAINS SURVEY BIAS.')
def measurement_menu():
  while True:
    key=STCORE.menu('STUDY > DATA TYPE',[('1','QUALITATIVE / QUANTITATIVE'),('2','DISCRETE / CONTINUOUS'),('3','MEASUREMENT LEVELS')])
    if key=='0': return
    if key=='1': definition_pages('STUDY > DATA TYPE','QUALITATIVE: CATEGORIES OR LABELS. QUANTITATIVE: NUMERICAL COUNTS OR MEASUREMENTS. A NUMBER USED ONLY AS AN ID IS A LABEL.')
    elif key=='2': definition_pages('STUDY > DATA TYPE','DISCRETE: COUNTABLE VALUES, LIKE NUMBER OF CHILDREN. CONTINUOUS: MEASUREMENTS THROUGH AN INTERVAL, LIKE HEIGHT.')
    elif key=='3': definition_list('STUDY > MEASUREMENT',MEASUREMENT_DEFINITIONS)
def significance_menu():
  while True:
    key=STCORE.menu('STUDY > SIGNIFICANCE',[('1','STATISTICAL VS PRACTICAL'),('2','ERROR DEFINITIONS'),('3','GIVEN p-VALUE: COMPARE alpha')])
    if key=='0': return
    if key=='1': definition_pages('STUDY > INTERPRETATION','STATISTICAL: p <= alpha MEANS THERE IS ENOUGH EVIDENCE TO REJECT H0. PRACTICAL: THE EFFECT IS LARGE ENOUGH TO MATTER IN REAL LIFE. CONSIDER ITS SIZE, COSTS AND CONSEQUENCES. A RESULT CAN BE STATISTICALLY SIGNIFICANT BUT TOO SMALL TO BE USEFUL.')
    elif key=='2': definition_list('STUDY > ERROR',STUDY_DEFINITIONS[:2])
    elif key=='3':
      p=STCORE.read_exact('p-VALUE: '); alpha=STCORE.read_exact('alpha: ')
      STCORE.results('STUDY > SIGNIFICANCE',[('STATISTICALLY SIGNIFICANT','YES' if STCORE.compare_exact(p,alpha)<=0 else 'NO'),('PRACTICALLY SIGNIFICANT','NEED EFFECT SIZE / CONTEXT')],['COMPARE p-VALUE <= alpha'])
def large_numbers():
  definition_pages('LAW OF LARGE NUMBERS','AS THE NUMBER OF INDEPENDENT TRIALS WITH THE SAME PROBABILITY BECOMES LARGE, RELATIVE FREQUENCY TENDS TO GET CLOSER TO THE TRUE PROBABILITY. SEE RELATIVE FREQUENCY AND EMPIRICAL PROBABILITY. THIS DOES NOT MEAN A LOSING STREAK MAKES A WIN DUE.')


def statistical_concepts():
  topics=[
    ('1','SAMPLING WITHOUT REPLACEMENT',
    'WITHOUT REPLACEMENT, SELECTIONS ARE DEPENDENT. IF n IS NO MORE THAN 5% OF POPULATION SIZE N, THE DEPENDENCE IS SMALL ENOUGH TO TREAT AS APPROXIMATELY INDEPENDENT. WITH REPLACEMENT, EACH DRAW CAN BE INDEPENDENT.'),
    ('2','CENTRAL LIMIT THEOREM CONDITIONS',
    'USE A RANDOM, INDEPENDENT SAMPLE. FOR SAMPLE MEANS, THE SAMPLING DISTRIBUTION IS NORMAL IF THE POPULATION IS NORMAL; FOR A NONNORMAL POPULATION, A LARGE n (COMMON RULE: n>=30) SUPPORTS A NORMAL APPROXIMATION. FOR SAMPLE PROPORTIONS, CHECK np>=10 AND n(1-p)>=10.'),
    ('3','STATISTIC OR PARAMETER?',
    'A VALUE CALCULATED FROM A SAMPLE IS A SAMPLE STATISTIC. A VALUE DESCRIBING THE ENTIRE POPULATION IS A PARAMETER. SAMPLE p-hat=x/n ESTIMATES POPULATION p; SAMPLE x-bar ESTIMATES POPULATION mu.'),
    ('4','SD OF THE SAMPLING DISTRIBUTION OF x-bar',
    'THE STANDARD DEVIATION OF ALL SAMPLE MEANS IS sigma_xbar=sigma/sqrt(n). IT IS CALLED THE STANDARD ERROR.'),
    ('5','BIASED OR UNBIASED ESTIMATORS',
    'SAMPLE PROPORTION p-hat ESTIMATES p WITHOUT BIAS. SAMPLE MEAN x-bar ESTIMATES mu WITHOUT BIAS. SAMPLE VARIANCE s^2 USING n-1 ESTIMATES sigma^2 WITHOUT BIAS. SAMPLE SD s IS BIASED FOR sigma (GENERALLY SLIGHTLY LOW). THIS IS ESTIMATOR BIAS, NOT SURVEY SELECTION BIAS.'),
    ('6','DOES POPULATION SIZE CHANGE REQUIRED n?',
    'FOR A LARGE POPULATION, THE USUAL SAMPLE-SIZE FORMULA DEPENDS ON CONFIDENCE, MARGIN OF ERROR, AND VARIABILITY, NOT TOTAL POPULATION SIZE. IF THE SAMPLE IS A SUBSTANTIAL FRACTION OF A FINITE POPULATION, A FINITE-POPULATION CORRECTION CAN REDUCE THE REQUIRED SAMPLE.'),
    ('7','CONFIDENCE INTERVAL AND MARGIN OF ERROR',
    'A CONFIDENCE INTERVAL IS A RANGE OF PLAUSIBLE VALUES FOR A POPULATION PARAMETER, MADE BY A PROCEDURE WITH A STATED LONG-RUN CONFIDENCE LEVEL. MARGIN OF ERROR IS THE DISTANCE FROM THE CENTER TO EITHER ENDPOINT. FOR ENDPOINTS L AND U: ESTIMATE=(L+U)/2; E=(U-L)/2.'),
    ('8','t INTERVAL ASSUMPTION WHEN n<30',
    'THE POPULATION SHOULD BE APPROXIMATELY NORMAL, WITH NO STRONG SKEWNESS OR EXTREME OUTLIERS. ALSO CHECK THAT THE SAMPLE IS RANDOM AND OBSERVATIONS ARE INDEPENDENT.')
  ]
  while True:
    labels=[
      '5% INDEPENDENCE RULE',
      'CLT CONDITIONS',
      'STATISTIC / PARAMETER',
      'SD OF x-bar',
      'BIASED / UNBIASED',
      'POPULATION SIZE',
      'CI / MARGIN ERROR',
      't ASSUMPTION n<30']
    key=STCORE.menu('STATISTICAL CONCEPTS',
            [(topics[i][0],labels[i]) for i in range(len(topics))])
    if key=='0': return
    for number,title,answer in topics:
      if key==number:
        definition_pages(title,answer)
        break
